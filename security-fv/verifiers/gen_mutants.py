#!/usr/bin/env python3
"""Negative controls: build deliberately broken copies of the Deposit verifier and check that the symbolic
properties FAIL on them (so a green run on the real verifiers is not vacuous).
Generates test/verifiers/VerifierMutants.t.sol. The `run_all.sh` runner requires every `check_mutant_*` to FAIL."""
import re
src = open("../packages/contracts/src/verifiers/DepositVerifier.sol").read()
body = src[src.index("contract DepositG16Base"):]

def mutate(text, tag):
    t = text.replace("DepositG16Base", f"{tag}DepositG16Base").replace("DepositVerifier", f"{tag}DepositVerifier")
    return t

m1 = mutate(body, "MissingCheck")
last = "checkField(calldataload(add(_pubSignals, 64)))"
assert last in m1
m1 = m1.replace(last, "// (mutant) last checkField removed")
m3 = mutate(body, "Rotated").replace("sigs[i] = uint256(publicInputs[i]);", "sigs[i] = uint256(publicInputs[(i + 1) % 3]);")
assert "(i + 1) % 3" in m3

hdr = '''// SPDX-License-Identifier: MIT
// GENERATED by verifiers/gen_mutants.py -- negative controls, never deployed.
pragma solidity ^0.8.24;
import {Test} from "forge-std/Test.sol";
import {ERC1967Proxy} from "@openzeppelin/contracts/proxy/ERC1967/ERC1967Proxy.sol";
import {IVerifier} from "polyshield/interfaces/IVerifier.sol";
import {DepositG16Base, DepositVerifier} from "polyshield/verifiers/DepositVerifier.sol";
import {Initializable} from "@openzeppelin/contracts/proxy/utils/Initializable.sol";
import {UUPSUpgradeable} from "@openzeppelin/contracts/proxy/utils/UUPSUpgradeable.sol";
import {OwnableUpgradeable} from "@openzeppelin-upgradeable/access/OwnableUpgradeable.sol";

interface MutSetter { function setBase(address) external; }
contract MutEcho3 {
    bytes32 immutable expected;
    constructor(bytes32 e) { expected = e; }
    function verifyProof(uint256[2] calldata a, uint256[2][2] calldata b, uint256[2] calldata c, uint256[3] calldata s)
        external view returns (bool) { return keccak256(abi.encode(a, b, c, s)) == expected; }
}

contract VerifierMutants is Test {
    uint256 internal constant R = 21888242871839275222246405745257275088548364400416034343698204186575808495617;

    // ---- negative control 1 (concrete, real proof): the field-bound check is what stops aliasing --------------
    function _fixture() internal view returns (bytes memory proof, uint256[3] memory sig) {
        string memory json = vm.readFile("../packages/contracts/test/fixtures/deposit_proof.json");
        proof = vm.parseJsonBytes(json, ".proof");
        string[] memory sigs = vm.parseJsonStringArray(json, ".signals");
        for (uint256 i = 0; i < 3; i++) sig[i] = vm.parseUint(sigs[i]);
    }

    function test_mutant_missingCheck_acceptsAliasedSignal_realRejects() public {
        (bytes memory proof, uint256[3] memory sig) = _fixture();
        (uint256[2] memory pA, uint256[2][2] memory pB, uint256[2] memory pC) = _decode(proof);
        MissingCheckDepositG16Base mutant = new MissingCheckDepositG16Base();
        DepositG16Base real = new DepositG16Base();
        // sanity: both accept the genuine proof
        assertTrue(mutant.verifyProof(pA, pB, pC, sig), "mutant accepts genuine proof");
        assertTrue(real.verifyProof(pA, pB, pC, sig), "real accepts genuine proof");
        // aliasing attack: last signal s2 -> s2 + r  (same value in F_r, different uint256)
        uint256[3] memory alias_ = [sig[0], sig[1], sig[2] + R];
        assertTrue(mutant.verifyProof(pA, pB, pC, alias_), "MUTANT (no field check) wrongly accepts the aliased signal");
        assertFalse(real.verifyProof(pA, pB, pC, alias_), "REAL verifier rejects the aliased signal");
    }

    // ---- negative control 2: reordering signals in the adapter breaks a genuine proof ------------------------
    function test_mutant_rotatedAdapter_rejectsGenuineProof_realAccepts() public {
        (bytes memory proof, uint256[3] memory sig) = _fixture();
        bytes32[] memory pub = new bytes32[](3);
        for (uint256 i = 0; i < 3; i++) pub[i] = bytes32(sig[i]);
        DepositVerifier real = DepositVerifier(address(new ERC1967Proxy(address(new DepositVerifier()),
            abi.encodeCall(DepositVerifier.initialize, (address(this))))));
        RotatedDepositVerifier rot = RotatedDepositVerifier(address(new ERC1967Proxy(address(new RotatedDepositVerifier()),
            abi.encodeCall(RotatedDepositVerifier.initialize, (address(this))))));
        assertTrue(real.verify(proof, pub), "real adapter accepts the genuine proof");
        assertFalse(rot.verify(proof, pub), "rotated-signal mutant rejects it");
    }

    function _decode(bytes memory p) internal pure returns (uint256[2] memory a, uint256[2][2] memory b, uint256[2] memory c) {
        (a, b, c) = abi.decode(p, (uint256[2], uint256[2][2], uint256[2]));
    }

    // ---- negative control 3 (symbolic): Halmos must produce a counterexample for the rotated adapter ----------
    function check_mutant_rotated_adapter(uint256[2] memory pA, uint256[2][2] memory pB, uint256[2] memory pC, uint256[3] memory s) public {
        RotatedDepositVerifier v = RotatedDepositVerifier(address(new ERC1967Proxy(address(new RotatedDepositVerifier()),
            abi.encodeCall(RotatedDepositVerifier.initialize, (address(this))))));
        MutEcho3 echo = new MutEcho3(keccak256(abi.encode(pA, pB, pC, s)));
        v.setBase(address(echo));
        bytes32[] memory pub = new bytes32[](3);
        for (uint256 k = 0; k < 3; k++) pub[k] = bytes32(s[k]);
        assertTrue(v.verify(abi.encode(pA, pB, pC), pub));
    }
}
'''
# the base+adapter text carries its own imports of IVerifier etc. -> strip duplicates by concatenating bodies only
open("test/verifiers/VerifierMutants.t.sol", "w").write(hdr + "\n" + m1 + "\n" + m3)
print("generated mutants")
