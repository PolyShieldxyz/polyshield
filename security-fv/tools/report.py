#!/usr/bin/env python3
"""Aggregate results/*.json + results/logs/* into results/RESULTS.md (the machine-generated evidence summary)."""
import glob, json, os, re, subprocess, datetime

RES = "results"
J = lambda p: json.load(open(p)) if os.path.exists(p) else None
strip = lambda s: re.sub(r"\x1b\[[0-9;]*m", "", s)
out = []
w = out.append


def sh(*a):
    try:
        return subprocess.run(a, capture_output=True, text=True).stdout.strip().splitlines()[0]
    except Exception:
        return "n/a"


HEAD = ["deposit", "bet_auth", "withdrawal", "settlement_credit", "bet_cancel", "cancel_credit", "position_close",
        "partial_credit", "consolidate"]
LIVE = ["bet_cancel_live", "cancel_credit_live", "partial_credit_live"]

w("# Formal-verification results (machine-generated)\n")
w(f"_Generated by `tools/report.py` from `run_all.sh` output on {datetime.date.today()}. Do not edit by hand._\n")
circ = {c: J(f"{RES}/circuits/{c}.json") for c in HEAD + LIVE}
z3v = next((v["z3"] for v in circ.values() if v and "z3" in v), "n/a")
w("| tool | version |\n|---|---|")
w(f"| circom | {open('build/circom.version').read().strip() if os.path.exists('build/circom.version') else 'n/a'} |")
w(f"| z3 | {z3v} |\n| halmos | {sh('halmos', '--version')} |\n| forge | {sh('forge', '--version')} |\n")

# ------------------------------------------------------------------ circuits
w("## 1. Circuits: security clauses proved against the R1CS\n")
w("`PROVED` = the solver showed `R1CS ∧ Poseidon-model ∧ ¬clause` is UNSAT. Clause text and the exact encoding assumptions are in "
  "[`../tools/specs.py`](../tools/specs.py).\n")
w("| circuit | R1CS constraints (O0) | Poseidon calls abstracted | clauses proved | non-vacuity | components mutated | components no clause depends on |")
w("|---|--:|--:|--:|---|--:|---|")
for c in HEAD + LIVE:
    d = circ[c]
    if not d:
        w(f"| {c} | – | – | – | – | – | _not run_ |"); continue
    cl = d["clauses"]; ok = sum(x["status"] == "PROVED" for x in cl)
    mm = d.get("mutation_matrix", {})
    red = [k for k, v in mm.items() if isinstance(v, dict) and not v["breaks"] and not v["unknown"]]
    tag = " (deployed on-chain)" if c.endswith("_live") else ""
    w(f"| `{c}`{tag} | {d['r1cs_constraints']} | {d['poseidon_calls']} | **{ok}/{len(cl)}** | {d['non_vacuity']} | {len(mm) or '–'} | {', '.join(red) or 'none'} |")
w("")
for c in HEAD + LIVE:
    d = circ[c]
    if not d: continue
    w(f"<details><summary><code>{c}</code> — clauses and mutation matrix</summary>\n")
    w("| status | time | clause |\n|---|--:|---|")
    for x in d["clauses"]:
        w(f"| {x['status']} | {x['seconds']}s | {x['clause']} |")
    mm = d.get("mutation_matrix")
    if mm:
        w("\n**Mutation matrix** — delete one component's constraints, re-check every clause; `breaks` = clauses that become violable:\n")
        w("| deleted component | clauses it protects |\n|---|--:|")
        for k, v in mm.items():
            w(f"| `{k}` | {len(v['breaks']) if isinstance(v, dict) else v}" + (f" (+{len(v['unknown'])} timeout)" if isinstance(v, dict) and v['unknown'] else "") + " |")
    w("\n</details>\n")

# ------------------------------------------------------------------ determinism
w("## 2. Circuits: under-constraint / uniqueness analysis\n")
w("| circuit | Poseidon instances functional | wires | unique by propagation | via SMT | inputs in no constraint | unexpected |\n|---|--:|--:|--:|--:|---|---|")
for f in ("determinism_head", "determinism_live"):
    d = J(f"{RES}/{f}.json")
    for c, r in (d or {}).items():
        w(f"| `{c}`{' (deployed)' if f.endswith('live') else ''} | {r['poseidon_instances'] - len(r['poseidon_not_functional'])}/{r['poseidon_instances']} | "
          f"{r['wires_in_system']} | {r['unique_by_propagation']} | {r['remaining_for_smt']} | {', '.join(r['inputs_in_no_constraint']) or '–'} | {', '.join(r['unexpected_free_inputs']) or 'none'} |")
w("")

# ------------------------------------------------------------------ differential
w("## 3. Toolchain validation against ground truth (real witnesses)\n")
d = J(f"{RES}/differential.json")
if d:
    w("Every case = valid inputs built with circomlibjs Poseidon, incl. boundary values; D1 wasm witness satisfies exact O0 and O2 R1CS · "
      "D2 O0 witness projects onto O2 R1CS · D3 identical public signals O0/O2 · D4 substitution consistent · D5 SMT encoding accepts the witness · D6 every clause holds.\n")
    w("| circuit | cases | D1 | D2 | D3 | D4 | D5 | D6 |\n|---|--:|--:|--:|--:|--:|--:|--:|")
    for c, r in d["report"].items():
        w(f"| `{c}` | {r['cases']} | {r['D1']} | {r['D2']} | {r['D3']} | {r['D4']} | {r['D5']} | {r['D6']} |")
    w(f"\nFailures: **{len(d['failures'])}**\n")

# ------------------------------------------------------------------ verifiers
w("## 4. Verifiers\n")
v = J(f"{RES}/verifiers.json")
if v:
    tot = sum(len(x) for x in v["results"].values())
    w(f"* Structural conformance (`verifiers/check_verifiers.py`): **{tot - len(v['failures'])}/{tot}** checks pass — base verifier == snarkjs 0.7.5 template(VK); adapter == pipeline `buildAdapter`; "
      "all VK points on curve / G2 in subgroup / IC count; public-signal order identical across R1CS, pipeline constants, adapter, `VaultInputs`; slot wiring.")
st = os.path.join(RES, "logs/verifier_selftest.log")
if os.path.exists(st):
    t = open(st).read()
    w(f"* Checker self-test: **{t.count('DETECTED')}/{t.count('DETECTED') + t.count('MISSED')}** injected defects detected.")
hl = os.path.join(RES, "logs/halmos_verifiers.log")
if os.path.exists(hl):
    t = strip(open(hl).read())
    w(f"* Halmos symbolic proofs: **{t.count('[PASS]')} passed, {t.count('[FAIL]')} failed** "
      "(P1 non-canonical public input ⇒ reject, base and adapter; P2 adapter forwards proof + signals verbatim).")
hm = os.path.join(RES, "logs/halmos_mutants.log")
if os.path.exists(hm):
    t = strip(open(hm).read())
    w(f"* Halmos negative control: broken adapter refuted with counterexample: **{'yes' if 'FAIL' in t else 'NO — investigate'}**.")
ft = os.path.join(RES, "logs/forge_test.log")
if os.path.exists(ft):
    t = strip(open(ft).read())
    m = re.search(r"(\d+) tests passed, (\d+) failed, (\d+) skipped", t)
    if m: w(f"* Foundry (real proofs, fuzz ×2000, cross-layer Poseidon/Merkle, negative controls): **{m.group(1)} passed, {m.group(2)} failed**.")
w("")

ll = os.path.join(RES, "logs/lean.log")
if os.path.exists(ll):
    t = open(ll).read()
    w(f"## 5. Lean (kernel-checked gadget lemmas)\n\n`lean/GadgetLemmas.lean` compiles with no errors / `sorry`; axioms audit: "
      f"{t.count('propext')} theorems depend only on standard axioms (see [`logs/lean.log`](logs/lean.log)).\n")
cs = os.path.join(RES, "logs/circomspect.txt")
if os.path.exists(cs):
    t = open(cs).read().strip().splitlines()
    w(f"## 6. circomspect (static linter, informational)\n\n`{t[-1] if t else ''}` — see [`logs/circomspect.txt`](logs/circomspect.txt).\n")
open(f"{RES}/RESULTS.md", "w").write("\n".join(out))
# scrub machine-specific absolute paths from committed logs/results
root = os.path.abspath("..")
for f in glob.glob(f"{RES}/**/*", recursive=True):
    if os.path.isfile(f) and f.endswith((".log", ".txt", ".json", ".md")):
        t = open(f, errors="replace").read()
        t2 = t.replace(root, "<repo>").replace(os.path.expanduser("~"), "~")
        if os.path.basename(f).startswith("halmos"):       # halmos dumps contract bytecode as hex; keep the verdict lines
            t2 = "\n".join(l for l in t2.splitlines() if not re.fullmatch(r"\s*[0-9a-f]{40,}\s*", strip(l)))
        if t2 != t:
            open(f, "w").write(t2)
print("wrote", f"{RES}/RESULTS.md")
